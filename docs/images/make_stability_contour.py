#!/usr/bin/env python3
"""Stability-contour figure for launch materials (HANDOFF-explainability-visibility.md, T3).

What this does
--------------
Produces ``docs/images/stability_contour.png`` (~1200 px wide): the package's default
response surface -- a stock, un-tuned RBF :class:`sklearn.gaussian_process.GaussianProcessRegressor`
-- fitted to a two-dimensional slice of the published benchmark search space on one
benchmark dataset.

The slice is ``rf__max_depth x rf__min_samples_leaf`` with ``rf__criterion`` fixed at its
first value (``"gini"``): exactly the suite's shared discrete space
(``benchmarks/DESIGN.md`` section 4) with one dimension pinned. The evaluation points are
generated by :class:`SKSurrogate.structsearch.SurrogateRandomCV` itself -- the product being
launched -- so the figure shows what the package does out of the box: a budget of candidate
fits (5-fold CV, ``StandardScaler + RandomForestClassifier(n_estimators=50)`` per
``benchmarks/methods.py::make_pipeline``) and the surrogate response surface fitted to them.

The GP is trained in exactly the coordinates that
:meth:`SKSurrogate.structsearch.SurrogateSearch` uses internally for its surrogate:
categorical parameters encoded as ordinal indices, linear scale (see
``_encode_value``/``_encoded_bounds`` in ``structsearch.py``). The package fits the surface
on negated accuracy; Gaussian process regression is linear in the target, so fitting on
accuracy and plotting the posterior mean yields the identical surface up to the sign we
choose for display. No external re-fit: this *is* the package's default response-surface model.

No new dependencies: scikit-learn/numpy are already required by SKSurrogate; matplotlib is
used only for output (present in the project dev environment).

Usage
-----
::

    PYTHONPATH=. .venv/bin/python docs/images/make_stability_contour.py [--dataset credit-g]

The defaults (``credit-g``, budget 48, seed 7) reproduce exactly the committed
``docs/images/stability_contour.png``. Run with a clean ``PYTHONPATH`` (a polluted one shadows
the venv's Pillow) and from inside the checkout (the script adds the repo root to ``sys.path``
itself). Deterministic for fixed ``--seed``/``--budget``: both Python's module-level ``random``
(SRS draws its x0 from it) and SKSurrogate are seeded, mirroring
``benchmarks/methods.py::_run_srs``.

Caption template -- the figure shows only this
------------------------------------------------
"Surrogate posterior mean of cross-validated accuracy over a two-dimensional hyperparameter
slice on <dataset>: rf__max_depth x rf__min_samples_leaf (rf__criterion fixed at 'gini'). The
points are evaluations performed by SKSurrogate's trust-region search (<n> candidate fits,
5-fold CV); the contours are the package's default un-tuned RBF Gaussian-process response
surface fitted to those points. This figure is about local curvature in hyperparameter space
(sharp peak vs flat plateau) -- it makes no claim about robustness to data drift or any
out-of-sample guarantee."

Verified caption for the shipped figure (credit-g, 48 fits, seed 7; surface statistics from a
seeded re-run of the identical fit): "Surrogate posterior mean of cross-validated accuracy
over a two-dimensional hyperparameter slice on credit-g (OpenML/31): rf__max_depth x
rf__min_samples_leaf (rf__criterion fixed at 'gini'). The 48 points are candidate fits evaluated
by SKSurrogate's surrogate-guided search with 5-fold cross-validation; the contours show the
package's default un-tuned RBF Gaussian-process response surface fitted to those points. On
this dataset high accuracy sits in a narrow corner of small tree depth and tiny min_samples_leaf
-- a sharp peak (only ~1% of the grid lies within 95% of the surface range) rather than a flat
plateau, with ~0.13 acc points of spread across leaf sizes at fixed depth. The figure shows local
curvature in hyperparameter space only; it makes no claim about robustness to data drift or any
out-of-sample guarantee." (An optdigits variant -- budget 36, seed 7 -- instead shows a broad
plateau: ~54% of the grid within 75% of range.)
"""

from __future__ import annotations

import argparse
import os
import random as _pyrandom
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.colors import Normalize  # noqa: E402
import numpy as np  # noqa: E402
from sklearn.gaussian_process import GaussianProcessRegressor  # noqa: E402

from SKSurrogate.structsearch import Categorical, SurrogateRandomCV  # noqa: E402

try:
    from benchmarks.datasets import load_dataset  # repo root must be on sys.path
    from benchmarks.methods import SPACE, make_pipeline
except ImportError as exc:  # pragma: no cover - guidance for running outside the checkout
    raise SystemExit(
        "benchmarks/ package not importable; run this script inside the sksurrogate checkout."
    ) from exc

OUT = Path(__file__).resolve().parent / "stability_contour.png"


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Stability-contour figure for launch materials (T3)."
    )
    parser.add_argument(
        "--dataset",
        default="credit-g",
        help=(
            "benchmark dataset name (see benchmarks/datasets.json); "
            "the shipped docs/images/stability_contour.png is credit-g, budget 48, seed 7"
        ),
    )
    parser.add_argument(
        "--budget", type=int, default=48, help="candidate fits SRS may spend"
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=7,
        help="search seed (kept outside the suite's per-seed record range 0-6)",
    )
    args = parser.parse_args()

    # Same determinism pinning as benchmarks/methods.py::_run_srs.
    _pyrandom.seed(1_000_003 + args.seed)

    X, y = load_dataset(args.dataset)

    # 2-D slice of the suite's shared discrete space (DESIGN.md section 4):
    # fix criterion at its first value; vary max_depth x min_samples_leaf.
    depth_values = list(SPACE["rf__max_depth"])
    leaf_values = list(SPACE["rf__min_samples_leaf"])
    fixed_criterion = SPACE["rf__criterion"][0]
    params = {
        "rf__max_depth": Categorical(depth_values),
        "rf__min_samples_leaf": Categorical(leaf_values),
        # pinned: the slice dimension (single-value categorical)
        "rf__criterion": Categorical([fixed_criterion]),
    }

    task_name = f"stability_fig_{args.dataset}_s{args.seed}"
    search = SurrogateRandomCV(
        estimator=make_pipeline(args.seed, n_estimators=50),
        params=params,
        # Safe ceiling (DESIGN.md v1.7 erratum); max_evals is the binding constraint.
        max_iter=4 * args.budget,
        max_evals=args.budget,
        min_evals=min(max(5, args.budget // 5), args.budget),  # suite default engagement
        regressor=None,  # library default since v0.2: stock un-tuned RBF GaussianProcessRegressor
        scoring=None,
        cv=5,
        refit=False,  # figure only; skip the full-dataset refit
        verbose=0,
        random_state=args.seed,
        n_jobs=1,
        warm_start=False,
        continue_=False,
        task_name=task_name,
    )
    search.fit(X, y)

    # SRS writes state checkpoint files to CWD; drop them (same as benchmarks/methods.py).
    for pkl in Path.cwd().glob(f"{task_name}*.pkl"):
        try:
            os.remove(pkl)
        except OSError:
            pass

    completed = [
        item
        for item in search.evaluation_history_
        if item.get("score") is not None and np.isfinite(item["score"])
    ]
    if len(completed) < 12:
        raise SystemExit(
            f"too few completed evaluations ({len(completed)}); slice run unusable."
        )

    # Replicate SRS surrogate coordinates (structsearch.py::_encode_value):
    # categorical parameters -> ordinal indices, linear scale.
    Xs = np.array(
        [
            [
                depth_values.index(item["params"]["rf__max_depth"]),
                leaf_values.index(item["params"]["rf__min_samples_leaf"]),
            ]
            for item in completed
        ],
        dtype=float,
    )
    ys_acc = np.array([-item["score"] for item in completed], dtype=float)

    gp = GaussianProcessRegressor()
    # GPR is linear in the target: fitting on accuracy gives the same surface (up to sign)
    # as the package's fit on negated accuracy, so the plotted field *is* the default
    # response-surface posterior mean.
    gp.fit(Xs, ys_acc)

    g1 = np.linspace(0.0, len(depth_values) - 1, 240)
    g2 = np.linspace(0.0, len(leaf_values) - 1, 160)
    G1, G2 = np.meshgrid(g1, g2)
    points = np.column_stack([G1.ravel(), G2.ravel()])
    mean_field = gp.predict(points).reshape(G1.shape)

    norm = Normalize(vmin=float(mean_field.min()), vmax=float(mean_field.max()))
    fig, ax = plt.subplots(figsize=(8.0, 5.0), dpi=150)  # -> exactly 1200 x 750 px
    cf = ax.contourf(G1, G2, mean_field, levels=24, cmap="viridis", norm=norm)
    cbar = fig.colorbar(cf, ax=ax)
    cbar.set_label("CV accuracy (surrogate posterior mean)")

    ax.scatter(
        Xs[:, 0],
        Xs[:, 1],
        s=38,
        c=ys_acc,
        cmap="viridis",
        norm=norm,
        edgecolors="k",
        linewidths=0.6,
        zorder=5,
    )

    best = int(np.argmax(ys_acc))
    ax.scatter(
        [Xs[best, 0]],
        [Xs[best, 1]],
        marker="*",
        s=260,
        facecolors="w",
        edgecolors="k",
        linewidths=1.0,
        zorder=6,
    )
    ax.annotate(
        f"best evaluated: {ys_acc[best]:.3f}",
        xy=(Xs[best, 0], Xs[best, 1]),
        xytext=(8, -14),
        textcoords="offset points",
        fontsize=9,
    )

    depth_tick_step = 2 if len(depth_values) > 6 else 1
    leaf_tick_step = 2 if len(leaf_values) > 8 else 1
    ax.set_xticks(range(0, len(depth_values), depth_tick_step))
    ax.set_xticklabels([str(v) for v in depth_values[::depth_tick_step]])
    ax.set_yticks(range(0, len(leaf_values), leaf_tick_step))
    ax.set_yticklabels([f"{v:g}" for v in leaf_values[::leaf_tick_step]])

    ax.set_xlabel("rf__max_depth")
    ax.set_ylabel("rf__min_samples_leaf")
    ax.set_title(
        f"Surrogate response surface - {args.dataset}, 2-D hyperparameter slice\n"
        f"({len(completed)} candidate fits, 5-fold CV; rf__criterion fixed at "
        f"'{fixed_criterion}'; seed {args.seed})",
        fontsize=10,
    )
    fig.tight_layout()
    fig.savefig(OUT, dpi=150)
    plt.close(fig)

    best_params = completed[best]["params"]
    print(f"dataset            : {args.dataset}")
    print(f"budget / evaluated : {args.budget} / {len(completed)}")
    print(f"slice              : max_depth x min_samples_leaf (criterion fixed '{fixed_criterion}')")
    print(
        "coverage           : depth idx [%d..%d], leaf idx [%d..%d]"
        % (int(Xs[:, 0].min()), int(Xs[:, 0].max()), int(Xs[:, 1].min()), int(Xs[:, 1].max()))
    )
    print(
        "best evaluated     : max_depth=%r min_samples_leaf=%r accuracy=%.4f"
        % (
            best_params["rf__max_depth"],
            best_params["rf__min_samples_leaf"],
            float(ys_acc[best]),
        )
    )
    print(f"output             : {OUT}")


if __name__ == "__main__":
    main()
